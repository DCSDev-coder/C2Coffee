CREATE TABLE IF NOT EXISTS outlet_emergency_closures (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id BIGINT UNSIGNED NOT NULL,
  store_id BIGINT UNSIGNED NOT NULL,
  barista_id INT NOT NULL,
  initiated_by_admin_user_id BIGINT UNSIGNED NOT NULL,
  idempotency_key VARCHAR(100) NOT NULL,
  reason_code VARCHAR(40) NOT NULL,
  note VARCHAR(500) NULL,
  status ENUM('active', 'reopened', 'auto_reopened') NOT NULL DEFAULT 'active',
  expected_reopen_at DATETIME NULL,
  reopened_at DATETIME NULL,
  reopened_by_barista_id INT NULL,
  reopened_by_admin_user_id BIGINT UNSIGNED NULL,
  cancelled_order_count INT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_outlet_emergency_idempotency (tenant_id, idempotency_key),
  KEY idx_outlet_emergency_active (tenant_id, store_id, status, created_at),
  KEY idx_outlet_emergency_reopen (status, expected_reopen_at),
  CONSTRAINT fk_outlet_emergency_tenant FOREIGN KEY (tenant_id) REFERENCES admin_tenants(id) ON DELETE CASCADE,
  CONSTRAINT fk_outlet_emergency_store FOREIGN KEY (store_id) REFERENCES stores(id) ON DELETE CASCADE,
  CONSTRAINT fk_outlet_emergency_barista FOREIGN KEY (barista_id) REFERENCES baristas(id) ON DELETE RESTRICT,
  CONSTRAINT fk_outlet_emergency_admin FOREIGN KEY (initiated_by_admin_user_id) REFERENCES admin_users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_outlet_emergency_reopen_barista FOREIGN KEY (reopened_by_barista_id) REFERENCES baristas(id) ON DELETE SET NULL,
  CONSTRAINT fk_outlet_emergency_reopen_admin FOREIGN KEY (reopened_by_admin_user_id) REFERENCES admin_users(id) ON DELETE SET NULL,
  CONSTRAINT chk_outlet_emergency_reason CHECK (reason_code IN ('medical_emergency', 'safety_incident', 'power_outage', 'equipment_failure', 'other'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
